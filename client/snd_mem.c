/*
================
ResampleSfx

Resample a freshly loaded sound into the output-rate cache.  Sounds already at
the output rate are copied through bit-exact; otherwise a polyphase Kaiser-
windowed-sinc kernel reconstructs them.  Linear interpolation only attenuates
the spectral images of Quake's low-rate effects (a sinc^2 rolloff); the
windowed-sinc rejects them by 70+ dB, removing the metallic imaging ("ringing")
of upsampled SFX.  It costs nothing at runtime (this runs once at load into the
cache) and uses no floats, so the cached samples stay bit-identical across
platforms - preserving the mixer/netplay/runahead determinism.
================
*/
void ResampleSfx (sfx_t *sfx, int inrate, int inwidth, byte *data)
{
	sfxcache_t	*sc;
	int		inlength, outcount, fracstep, samplefrac, i;

	sc = sfx->cache;
	if (!sc)
		return;

	inlength = sc->length;

	/* 16.16 step and output length in integer math (no float), so the cached
	 * length and sub-sample phase are identical on every target */
	fracstep = (int)(((int64_t)inrate << 16) / dma.speed);
	if (fracstep < 1)
		fracstep = 1;
	outcount = (int)(((int64_t)inlength * dma.speed) / inrate);

	sc->length = outcount;
	if (sc->loopstart != -1)
		sc->loopstart = (int)(((int64_t)sc->loopstart * dma.speed) / inrate);

	sc->speed = dma.speed;
	sc->width = inwidth;
	sc->stereo = 0;

	if (fracstep == (1 << 16))
	{
		/* source already at the output rate: bit-exact pass-through */
		for (i = 0; i < outcount; i++)
		{
			int s = (inwidth == 2)
				? LittleShort(((short *)data)[i])
				: (((int)(unsigned char)data[i] - 128) << 8);
			if (sc->width == 2)
				((short *)sc->data)[i] = s;
			else
				((signed char *)sc->data)[i] = s >> 8;
		}
		return;
	}

	samplefrac = 0;
	for (i = 0; i < outcount; i++)
	{
		int	base  = samplefrac >> 16;
		int	phase = (samplefrac >> 8) & 0xFF;
		int	csum  = 0;
		int	k, kh, ti, c, idx, s, sample;
		int64_t	acc = 0;

		if (fracstep <= (1 << 16))
		{
			/* up-sampling / unity: kernel at source-sample spacing, cutoff at
			 * the source Nyquist */
			for (k = -(SFX_RS_NZ - 1); k <= SFX_RS_NZ; k++)
			{
				ti = k * SFX_RS_SUB - phase;
				if (ti < 0)
					ti = -ti;
				if (ti > SFX_RS_MAX)
					continue;
				c = s_sfx_sinc[ti];
				idx = base + k;
				if (idx < 0)
					idx = 0;
				else if (idx >= inlength)
					idx = inlength - 1;
				s = (inwidth == 2)
					? LittleShort(((short *)data)[idx])
					: (((int)(unsigned char)data[idx] - 128) << 8);
				acc  += (int64_t)c * s;
				csum += c;
			}
		}
		else
		{
			/* down-sampling: stretch the kernel by the ratio so the cutoff
			 * tracks the lower output Nyquist and rejects aliasing */
			kh = (int)(((int64_t)SFX_RS_NZ * fracstep) >> 16) + 2;
			for (k = -kh; k <= kh; k++)
			{
				ti = k * SFX_RS_SUB - phase;
				if (ti < 0)
					ti = -ti;
				ti = (int)(((int64_t)ti << 16) / fracstep);
				if (ti > SFX_RS_MAX)
					continue;
				c = s_sfx_sinc[ti];
				idx = base + k;
				if (idx < 0)
					idx = 0;
				else if (idx >= inlength)
					idx = inlength - 1;
				s = (inwidth == 2)
					? LittleShort(((short *)data)[idx])
					: (((int)(unsigned char)data[idx] - 128) << 8);
				acc  += (int64_t)c * s;
				csum += c;
			}
		}

		/* normalise to unity gain (csum ~ SFX_RS_ONE), symmetric rounding */
		if (csum > 0)
		{
			if (acc >= 0)
				sample = (int)((acc + (csum >> 1)) / csum);
			else
				sample = -(int)(((-acc) + (csum >> 1)) / csum);
		}
		else
			sample = 0;

		if (sample > 32767)
			sample = 32767;
		else if (sample < -32768)
			sample = -32768;

		if (sc->width == 2)
			((short *)sc->data)[i] = sample;
		else
			((signed char *)sc->data)[i] = sample >> 8;

		samplefrac += fracstep;
	}
}

